#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_are_sorted_for_lookup() {
        for t in [SYMBOL, WINGDINGS, WINGDINGS_2] {
            assert!(t.windows(2).all(|w| w[0].0 < w[1].0));
        }
    }

    #[test]
    fn codes_read_as_what_they_show() {
        assert_eq!(char_for("Wingdings", 0xF0E0), Some('→'));
        assert_eq!(char_for("Wingdings", 0xF0DF), Some('←'));
        assert_eq!(char_for("Wingdings", 0xF0A8), Some('☐'));
        assert_eq!(char_for("Wingdings", 0xF0FE), Some('☑'));
        assert_eq!(char_for("Symbol", 0xF0B0), Some('°'));
        assert_eq!(char_for("Symbol", 0xF0B1), Some('±'));
        assert_eq!(char_for("symbol", 'm' as u32), Some('μ'));
        assert_eq!(char_for("Wingdings 2", 0xF052), Some('☑'));
        assert_eq!(char_for("Arial", 0xF0B0), None);
    }
}
