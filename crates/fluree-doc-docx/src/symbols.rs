//! Characters set in Word's symbol fonts, as the Unicode characters they
//! show.
//!
//! Word's Insert Symbol stores a character from Symbol or Wingdings as the
//! font's own code, `<w:sym w:font="Wingdings" w:char="F0E0"/>`, not as a
//! character: the code is a glyph's position in that font, and in any other
//! font it is nothing. Read as text it is lost, and with it an arrow on a
//! pass/fail scale, a `°` or `±` in a limit, or a batch record's check
//! boxes. A run set in one of those fonts is the same: `m` typed in Symbol
//! shows `μ`.
//!
//! Symbol is mapped in full. Of the Wingdings, the characters documents
//! actually write with are: arrows, check marks and boxes, bullets, hands,
//! circled numbers. Each goes to the character a reader would search for —
//! `→`, `☐`, `☑` — where Unicode's own mapping of the font names a
//! decorated variant (`🡪`, `🗹`) that means the same.

/// The character a symbol font's code shows, if the font is one of these
/// and the code is mapped. `code` is the font's own code, `0x20`–`0xFF`;
/// Word adds `0xF000` to it, which is stripped here.
pub fn char_for(font: &str, code: u32) -> Option<char> {
    let code = if (0xF000..=0xF0FF).contains(&code) {
        code - 0xF000
    } else {
        code
    };
    if !(0x20..=0xFF).contains(&code) {
        return None;
    }
    let font = font.trim().to_ascii_lowercase();
    let table: &[(u8, char)] = match font.as_str() {
        "symbol" => SYMBOL,
        "wingdings" => WINGDINGS,
        "wingdings 2" => WINGDINGS_2,
        _ => return None,
    };
    table
        .binary_search_by_key(&(code as u8), |&(k, _)| k)
        .ok()
        .map(|i| table[i].1)
}

/// Whether text set in this font is written in its own codes.
pub fn is_symbol_font(font: &str) -> bool {
    matches!(
        font.trim().to_ascii_lowercase().as_str(),
        "symbol" | "wingdings" | "wingdings 2"
    )
}

